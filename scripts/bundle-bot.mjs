import { existsSync, readdirSync, statSync } from "node:fs";
import { build } from "esbuild";

/**
 * Builds the single-file bot bundle committed at the repository root.
 * The production host cannot run `npm install`, so every runtime dependency
 * except optional native addons is bundled here.
 */
const EXTERNALS = [
  "zlib-sync",
  "bufferutil",
  "utf-8-validate",
  "erlpack",
  "@discordjs/opus",
  "sodium-native",
  "pino-pretty",
];

const MAX_BUNDLE_BYTES = 20 * 1024 * 1024;

await build({
  entryPoints: ["src/index.ts"],
  outfile: "index.js",
  bundle: true,
  platform: "node",
  target: "node20",
  format: "cjs",
  keepNames: true,
  sourcemap: false,
  legalComments: "eof",
  logLevel: "info",
  external: EXTERNALS,
  banner: {
    js: "// Generated by scripts/bundle-bot.mjs — do not edit. Source: src/",
  },
});

const bytes = statSync("index.js").size;
const megabytes = bytes / 1024 / 1024;

console.log(`bundle: ${megabytes.toFixed(2)} MB (index.js)`);

if (bytes > MAX_BUNDLE_BYTES) {
  console.error(`Bundle is larger than the ${MAX_BUNDLE_BYTES / 1024 / 1024} MB gate.`);
  process.exit(1);
}
